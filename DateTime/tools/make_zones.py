#!/usr/bin/env python3
"""OpenDateTime's table of places: each zone in the tz database's zone.tab, with
the POSIX rule its TZif file ends with (the offset and, where there is one,
summer time: when it starts and ends). The editor shows the places; its
background part (KEEP) runs the rules on a real Amiga.

    DateTime/tools/make_zones.py [ZONEINFO] > DateTime/src/zones.h

ZONEINFO is the host's tz data, /usr/share/zoneinfo by default. The tz
database is in the public domain. Nothing is fetched.

MIT, Copyright (c) 2026 AmigaChrome Team.
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

PLACE_MAX = 40          # struct ZonePrefs' zp_Place, with its NUL
RULE_MAX = 56           # and zp_Rule


def footer(path: Path) -> str:
    """The POSIX rule at the end of a TZif version 2 or later file."""
    data = path.read_bytes()
    if data[:4] != b"TZif" or data[4:5] not in (b"2", b"3", b"4"):
        raise ValueError(f"{path}: not TZif 2 or later")
    end = data.rstrip(b"\n")
    rule = end[end.rindex(b"\n") + 1:].decode("ascii")
    if not rule:
        raise ValueError(f"{path}: no POSIX rule at the end")
    return rule


FROM = 1767225600       # 1 January 2026, UTC: changes listed from here


def transitions(path: Path) -> list[tuple[int, int, int]]:
    """The changes a TZif file lists in its 64-bit part: (UTC seconds, offset east, summer time)."""
    data = path.read_bytes()

    def counts(at):
        return struct.unpack_from(">6l", data, at + 20)

    isut, isstd, leap, timecnt, typecnt, charcnt = counts(0)
    at = 44 + timecnt * 5 + typecnt * 6 + charcnt + leap * 8 + isstd + isut     # past the 32-bit part
    if data[at:at + 4] != b"TZif":
        raise ValueError(f"{path}: no 64-bit part")
    isut, isstd, leap, timecnt, typecnt, charcnt = counts(at)
    at += 44
    times = struct.unpack_from(f">{timecnt}q", data, at)
    at += timecnt * 8
    idx = data[at:at + timecnt]
    at += timecnt
    types = [struct.unpack_from(">lBB", data, at + 6 * i)[:2] for i in range(typecnt)]
    return [(t, types[i][0], types[i][1]) for t, i in zip(times, idx)]


def listed(path: Path, rule: str) -> list[tuple[int, int, int]]:
    """The changes from 2026 the rule can't say: a rule with no summer time says no
    change, so any the file lists after 2026 are listed here, with the offset in force
    on 1 January 2026 first. A rule with summer time is taken as it is (the host tests
    check it against the host's tz data, hour by hour)."""
    if "," in rule:
        return []
    ts = transitions(path)
    later = [t for t in ts if t[0] > FROM]
    if not later:
        return []
    before = [t for t in ts if t[0] <= FROM]
    first = (FROM, before[-1][1], before[-1][2]) if before else (FROM, later[0][1], later[0][2])
    return [first] + later


def version(root: Path) -> str:
    zi = root / "tzdata.zi"
    if zi.exists():
        first = zi.read_text(encoding="ascii", errors="replace").splitlines()[0]
        if first.startswith("# version "):
            return first[len("# version "):].strip()
    return "unknown"


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo")
    names = set()
    for line in (root / "zone.tab").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            names.add(line.split("\t")[2])
    names.add("UTC")
    zones = []
    changes = []                                   # one list per set of changes, shared by places with the same
    for name in sorted(names):
        rule = footer(root / name)
        if len(name) >= PLACE_MAX or len(rule) >= RULE_MAX:
            raise ValueError(f"{name} {rule}: too long for ZonePrefs")
        mine = listed(root / name, rule)
        first = 0
        if mine:
            flat = [c for run in changes for c in run]
            n = next((i for i in range(len(flat) - len(mine) + 1) if flat[i:i + len(mine)] == mine), None)
            if n is None:
                n = len(flat)
                changes.append(mine)
            first = n
        zones.append((name, rule, first, len(mine)))
    flat = [c for run in changes for c in run]
    rules = sorted({z[1] for z in zones})
    index = {r: i for i, r in enumerate(rules)}
    if len(rules) > 255:
        raise ValueError("more than 255 rules: zone_table's rule is a UBYTE")
    out = sys.stdout
    out.write("/* OpenDateTime's places: generated by DateTime/tools/make_zones.py from the tz database\n"
              f" * {version(root)} (public domain): every zone in zone.tab, and UTC, with the POSIX rule\n"
              " * its TZif file ends with, and the changes from 2026 a rule can't say (tzrule.c's\n"
              " * struct tz_change). Don't edit: run the script again.\n"
              " * MIT, Copyright (c) 2026 AmigaChrome Team. */\n")
    out.write(f'#define ZONES_TZDATA "{version(root)}"\n')
    out.write(f"#define ZONE_RULES {len(rules)}\n#define ZONE_COUNT {len(zones)}\n#define ZONE_CHANGES {max(len(flat), 1)}\n\n")
    out.write("static const char *const zone_rules[ZONE_RULES] = {\n")
    for r in rules:
        out.write(f'    "{r}",\n')
    out.write("};\n\n")
    out.write("static const struct tz_change zone_changes[ZONE_CHANGES] = {\n")
    for when, east, dst in flat or [(0, 0, 0)]:
        out.write(f"    {{ {when}UL, {east}L, {dst} }},\n")
    out.write("};\n\n")
    out.write("static const struct zone_place {\n    const char *name;\n    unsigned char rule;              /* in zone_rules */\n"
              "    unsigned short first, changes;   /* in zone_changes */\n} zone_table[ZONE_COUNT] = {\n")
    for name, rule, first, n in zones:
        out.write(f'    {{ "{name}", {index[rule]}, {first}, {n} }},\n')
    out.write("};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
